def get_daily_mood(seed: Optional[int] = None) -> dict:
    """
    用日期作为随机种子，每天返回固定的一条底色心情。
    seed 可以手动传入（用于测试）。
    """
    import datetime
    if seed is None:
        today = datetime.date.today()
        seed = int(today.strftime("%Y%m%d"))
    rng = random.Random(seed)
    desc, valence, arousal = rng.choice(MOOD_POOL)
    return {
        "description": desc,
        "valence": valence,
        "arousal": arousal,
    }


def get_random_mood() -> dict:
    """随机返回一条心情（不绑定日期，用于测试）。"""
    desc, valence, arousal = random.choice(MOOD_POOL)
    return {
        "description": desc,
        "valence": valence,
        "arousal": arousal,
    }
